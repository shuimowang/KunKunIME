#!/usr/bin/env python3
"""Assemble Android assets from this checkout's shared data; no downloads.

The output directory is generated and ignored by Git. Mobile-owned layouts and
settings live in android/assets; shared dictionaries stay in WindInput/data.
Requires Python 3.11 or newer, with no third-party Python dependencies.
"""
from __future__ import annotations

import copy
import hashlib
import json
import math
from pathlib import Path
import shutil
import tomllib


ANDROID = Path(__file__).resolve().parents[1]
REPO = ANDROID.parent
SHARED = REPO / "WindInput/data"
MOBILE = ANDROID / "assets/data"
OUTPUT = ANDROID / "app/src/main/assets/data"


def merge(base: dict, overlay: dict) -> dict:
    for key, value in overlay.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            merge(base[key], value)
        else:
            base[key] = copy.deepcopy(value)
    return base


def quoted(value: str) -> str:
    # JSON basic strings are also TOML basic strings for the configuration's
    # Unicode text and escape sequences. Preserve non-ASCII dictionary names.
    return json.dumps(value, ensure_ascii=False)


def value_toml(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return quoted(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float) and math.isfinite(value):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(value_toml(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{quoted(k)} = {value_toml(v)}" for k, v in value.items()) + " }"
    raise ValueError(f"Unsupported configuration value: {type(value).__name__}")


def dump_toml(data: dict) -> str:
    lines = ["# Generated by android/scripts/prepare-assets.py; edit the source defaults."]

    def table(values: dict, path: tuple[str, ...]) -> None:
        if path:
            lines.extend(["", "[" + ".".join(map(quoted, path)) + "]"])
        for key, value in values.items():
            if not isinstance(value, dict):
                lines.append(f"{quoted(key)} = {value_toml(value)}")
        for key, value in values.items():
            if isinstance(value, dict):
                table(value, (*path, key))

    table(data, ())
    text = "\n".join(lines) + "\n"
    if tomllib.loads(text) != data:
        raise ValueError("Generated TOML changed a configuration value")
    return text


def prepare() -> None:
    sources = [
        SHARED / "config.toml",
        REPO / "WindInput/data_custom/config.toml",
        ANDROID / "assets/engine-overrides.toml",
    ]
    config: dict = {}
    for source in sources:
        merge(config, tomllib.loads(source.read_text(encoding="utf-8")))
    for schema in config["schema"]["available"]:
        if not (SHARED / f"schemas/{schema}.schema.toml").is_file():
            raise FileNotFoundError(f"Missing shared input schema: {schema}")
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    shutil.copytree(SHARED, OUTPUT)
    shutil.copytree(MOBILE, OUTPUT, dirs_exist_ok=True)
    (OUTPUT / "config.toml").write_text(dump_toml(config), encoding="utf-8")

    # Preserve the product dictionary notices, including KunKunIME's CMUdict
    # English vocabulary, alongside the mobile app's own notices.
    notices = OUTPUT / "licenses"
    shutil.copytree(REPO / "licenses", notices, dirs_exist_ok=True)
    shutil.copy2(REPO / "ORIGINS.md", notices / "ORIGINS.md")
    shutil.copy2(REPO / "LICENSE", notices / "GPL-3.0.txt")

    manifest = {
        str(p.relative_to(OUTPUT)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(OUTPUT.rglob("*")) if p.is_file()
    }
    (OUTPUT / "asset-manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Prepared {len(manifest)} assets from the shared KunKunIME checkout")


if __name__ == "__main__":
    prepare()
